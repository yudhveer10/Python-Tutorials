#OPERATORS IN Python

a= 34
b= 2

#Arithematic Operators
print("a + b= ", a + b)
print("a - b= ", a - b)
print("a * b= ", a * b)
print("a / b= ", a / b)
print("a % b= ", a % b)
print("a ** b= ", a ** b)

#Conditional Operators
print(a>4)
print(a<4)
print(a>=4)
print(a<=4)
print(a==4)
print(a==34)
print(a!=34)

#Logical Operator
c = True
d = False
print(c and c)
print(d and d)
print(d and c)
print(c and d)
